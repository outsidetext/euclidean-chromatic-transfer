# Generate j0 Chebyshev table: interval k = [k*H, (k+1)*H], degree D interpolant at Chebyshev nodes, monomial
# coefficients in u = (x - mid)/(H/2) in [-1,1]. Values from mpmath at 40 digits; coefficients via exact-ish
# solve in mpmath, then rounded to double.
import mpmath as mp, sys
mp.mp.dps = 40
H = mp.mpf(1) / 8; D = 8; XMAX = 1024; NI = int(XMAX * 8)
nodes = [mp.cos(mp.pi * (2 * j + 1) / (2 * (D + 1))) for j in range(D + 1)]
# Vandermonde inverse for the fixed nodes (same for all intervals)
V = mp.matrix([[u ** i for i in range(D + 1)] for u in nodes]); Vi = V ** -1
out = open('j0_table.h', 'w')
out.write(f'// generated by gen_table.py: J0 on [0,{XMAX}), {NI} intervals of width 1/8, degree {D} in u=(x-mid)*16\n')
out.write(f'#define J0T_NI {NI}\n#define J0T_D {D}\nstatic const double J0T[{NI}][{D+1}] = {{\n')
for k in range(NI):
    mid = (k + mp.mpf(1) / 2) * H
    vals = mp.matrix([mp.besselj(0, mid + u * H / 2) for u in nodes])
    c = Vi * vals
    out.write('{' + ','.join(repr(float(ci)) for ci in c) + '},\n')
    if k % 1024 == 0: print(k, file=sys.stderr, flush=True)
out.write('};\n'); out.close()
